def log(s): LOG.append(s); print(s)


_Q = {'“': '"', '”': '"'}


def _norm(t):
    for k, v in _Q.items():
        t = t.replace(k, v)
    return t


def find_para_loose(raw, needle):
    n = _norm(needle)
    for i, (a, b) in enumerate(para_spans(raw)):
        if n in _norm(para_text(raw, a, b).strip()):
            return i, a, b
    raise ValueError('未找到段落（引号无关）：' + needle[:50])


def rewrite_para_loose(raw, needle, parts):
    i, a, b = find_para_loose(raw, needle)
    return raw[:a] + build_para(raw[a:b], parts) + raw[b:], i


def rewrite_cells(raw, caption_needle, texts, skip=0):
    """按位置重写 caption 之后的 N 个单元格段落（表格行列顺序）"""
    _, _, cb = find_para_loose(raw, caption_needle)
    spans = para_spans(raw)
    start = None
    for k, (a, b) in enumerate(spans):
        if a >= cb:
            start = k
            break
    # 注意：必须从后往前替换，否则前一次重建改变长度会让后续偏移失效（曾吞掉 </w:tbl>）
    for j in range(len(texts) - 1, -1, -1):
        a, b = spans[start + skip + j]
        raw = raw[:a] + build_para(raw[a:b], [(texts[j], False)]) + raw[b:]
    return raw


# ─────────────────────────────── A 引号
def stage_A():
    global W
    idxs = []
    for a, b in para_spans(W):
        for m in re.finditer(r'[“”]', W[a:b]):
            idxs.append((a + m.start(), m.group(0)))
    expect_open, edits = True, []
    for pos, ch in idxs:
        want = '“' if expect_open else '”'
        if ch != want:
            edits.append((pos, want))
        expect_open = not expect_open
    for pos, want in reversed(edits):
        W = W[:pos] + want + W[pos + 1:]
    log('【A】引号修复：%d 个引号，改动 %d 处' % (len(idxs), len(edits)))


# ─────────────────────────────── B 题注居中
CAP_RE = re.compile(r'^(图|表)(\d+)-(\d+)\s*(.*)$')
BADPUNCT = '。？！，；：'


def stage_B():
    global W
    TBL = [(m.start(), m.end()) for m in re.finditer(r'<w:tbl>.*?</w:tbl>', W, re.S)]
    edits = []
    for a, b in para_spans(W):
        if any(x <= a < y for x, y in TBL):
            continue
        t = para_text(W, a, b).strip()
        if len(t) > 45:
            continue
        m = CAP_RE.match(t)
        if not m:
            continue
        rest = m.group(4).strip()
        if not rest or any(c in rest for c in BADPUNCT) or len(rest) > 32:
            continue
        jc = re.search(r'<w:jc w:val="([^"]+)"', W[a:b])
        if jc and jc.group(1) == 'center':
            continue
        edits.append((a, b, set_center(W[a:b])))
    for a, b, seg in sorted(edits, reverse=True):
        W = W[:a] + seg + W[b:]
    log('【B】题注居中：%d 条' % len(edits))


# ─────────────────────────────── C 标题层级
def stage_C():
    global W
    edits = []
    for a, b in para_spans(W):
        t = para_text(W, a, b).strip()
        if not t:
            continue
        m = re.search(r'w:pStyle w:val="(\d+)"', W[a:b])
        if not m:
            continue
        old, new = m.group(1), None
        if old == '4' and re.match(r'^任务5\.\d', t):
            new = '2'
        elif old == '5' and re.match(r'^5\.\d+\.\d+', t):
            new = '4'
        elif old == '6' and re.match(r'^\d+\.\s*', t):
            new = '5'
        if new:
            edits.append((a, b, old, new))
    for a, b, old, new in sorted(edits, reverse=True):
        seg = re.sub(r'(w:pStyle w:val=")%s(")' % old, r'\g<1>%s\g<2>' % new, W[a:b], count=1)
        W = W[:a] + seg + W[b:]
    log('【C】标题层级修正：%d 处（任务 4→2；5.x.x 5→4；"1." 6→5）' % len(edits))


