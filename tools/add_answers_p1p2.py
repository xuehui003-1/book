def main():
    for job in JOBS:
        shutil.rmtree(job['work'], ignore_errors=True)
        os.makedirs(job['work'] + '/out', exist_ok=True)
        Z = zipfile.ZipFile(job['src'])
        names = Z.namelist()
        Z.extractall(job['work'] + '/work')
        W = open(job['work'] + '/work/word/document.xml', encoding='utf-8').read()

        paras = [mk_para(t, s) for t, s in job['blocks']]
        W, i = prepend_paras(W, job['anchor'], paras)
        print('  ✔ %s：在「%s」之前插入 %d 段（三、参考答案（要点））'
              % (job['dst'][:30], job['anchor'], len(paras)))

        open(job['work'] + '/work/word/document.xml', 'w', encoding='utf-8').write(W)
        out = job['work'] + '/out/' + job['dst']
        with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as zo:
            for n in names:
                zo.write(os.path.join(job['work'] + '/work', n), n)
        print('     已生成：%s  (%.1f KB)' % (out, os.path.getsize(out) / 1024))


if __name__ == '__main__':
    main()
