def main():
    for src, dst, work, edits in JOBS:
        shutil.rmtree(work, ignore_errors=True)
        os.makedirs(work + '/out', exist_ok=True)
        Z = zipfile.ZipFile(src)
        names = Z.namelist()
        Z.extractall(work + '/work')
        f = work + '/work/word/document.xml'
        raw = open(f, encoding='utf-8').read()
        miss = []
        for old, new in edits:
            raw, n = replace_text_nodes(raw, old, new)
            if not n:
                miss.append(old[:36])
        raw, _ = normalize_punct_docx(raw)
        open(f, 'w', encoding='utf-8').write(raw)
        out = work + '/out/' + dst
        with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as zo:
            for m in names:
                zo.write(os.path.join(work + '/work', m), m)
        print('【%s】改 %d 条%s → %s' % (dst, len(edits) - len(miss),
                                        ('，未命中 %d 条：%s' % (len(miss), '；'.join(miss))) if miss else '',
                                        out))


if __name__ == '__main__':
    main()
