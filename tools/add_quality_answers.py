LABEL = '素质测评参考要点：'


def append_at_end(raw, paras_xml):
    """在最后一个有文字的段落之后插入（项目3 无“项目X完”标记）"""
    last = None
    for a, b in para_spans(raw):
        if para_text(raw, a, b).strip():
            last = (a, b)
    return raw[:last[1]] + ''.join(paras_xml) + raw[last[1]:]


def main():
    for src, dst, work, marker, lbl_style, numbered, items, item_style in JOBS:
        shutil.rmtree(work, ignore_errors=True)
        os.makedirs(work + '/out', exist_ok=True)
        Z = zipfile.ZipFile(src)
        names = Z.namelist()
        Z.extractall(work + '/work')
        f = work + '/work/word/document.xml'
        raw = open(f, encoding='utf-8').read()

        paras = [mk_para(LABEL, lbl_style)] + [mk_para(t, item_style) for t in items]
        if marker:
            raw, i = prepend_paras(raw, marker, paras)
            where = '插在「%s」之前，位置 [%d]' % (marker, i)
        else:
            raw = append_at_end(raw, paras)
            where = '追加到文末'
        raw, _n = normalize_punct_docx(raw, verbose=True)
        open(f, 'w', encoding='utf-8').write(raw)
        out = work + '/out/' + dst
        with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as zo:
            for m in names:
                zo.write(os.path.join(work + '/work', m), m)
        print('【%s】+%d 段（%s）→ %s (%.1f KB)' % (dst, len(paras), where, out, os.path.getsize(out) / 1024))


if __name__ == '__main__':
    main()
