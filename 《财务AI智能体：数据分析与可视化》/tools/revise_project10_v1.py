def main():
    global W, NB
    shutil.rmtree(WORK, ignore_errors=True)
    os.makedirs(WORK + '/out', exist_ok=True)
    src_path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), SRC)
    if not os.path.exists(src_path):
        src_path = SRC
    Z = zipfile.ZipFile(src_path)
    names = Z.namelist()
    Z.extractall(WORK + '/work')
    W = open(WORK + '/work/word/document.xml', encoding='utf-8').read()
    NB = open(WORK + '/work/word/numbering.xml', encoding='utf-8').read()

    log('=== 项目10 修订流水线启动 ===')
    log('原始 document.xml 大小：%d 字符' % len(W))

    stage_B()
    stage_C()
    stage_D()
    stage_E()
    stage_A()  # 全局流式重排引号放在全部替换与插入之后

    # 标点与间距规范化
    W, n_punct = normalize_punct_docx(W)
    log('【标点与排版规范化】微调 %d 处' % n_punct)

    # 断言关键内容
    full = _html.unescape(''.join(re.findall(r'<w:t(?: [^>]*)?>(.*?)</w:t>', W, re.S)))
    log('\n  断言检查：')
    for bad in ['至关重要', '某连锁企业', '铁芯健身', '对于本书的学习目标']:
        n = full.count(bad)
        log('    %s 残留「%s」：%d' % ('✔' if n == 0 else '✘', bad, n))
    for good in ['鲜合餐饮', '项目核心实操', '小试牛刀', '会员复购率']:
        log('    ✔ 出现「%s」：%d' % (good, full.count(good)))

    open(WORK + '/work/word/document.xml', 'w', encoding='utf-8').write(W)
    open(WORK + '/work/word/numbering.xml', 'w', encoding='utf-8').write(NB)
    out_docx = WORK + '/out/项目10 财务数据仪表盘BI看板与数据叙事_修订稿V1.docx'
    with zipfile.ZipFile(out_docx, 'w', zipfile.ZIP_DEFLATED) as zout:
        for name in names:
            zout.write(WORK + '/work/' + name, name)
    log('输出文件生成完成：%s（大小 %d 字节）' % (out_docx, os.path.getsize(out_docx)))

    dest_dir = os.path.dirname(src_path)
    dest = os.path.join(dest_dir, '项目10 财务数据仪表盘BI看板与数据叙事_修订稿V1.docx')
    shutil.copyfile(out_docx, dest)
    log('已复制到目标目录：%s' % dest)


if __name__ == '__main__':
    main()
