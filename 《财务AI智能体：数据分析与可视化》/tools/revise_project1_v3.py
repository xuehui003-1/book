def rep_para(raw, old, new):
    """按整段文本定位，整段重建替换"""
    i, a, b = find_para(raw, old, exact=False)
    return raw[:a] + rebuild_para(raw[a:b], new, RPR) + raw[b:], i


def rep_t(raw, old, new):
    """在单个 <w:t> 内替换"""
    s, e = find_in_t(raw, old)
    return raw[:s] + new + raw[e:]


