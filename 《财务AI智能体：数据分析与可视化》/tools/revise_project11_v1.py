# ─────────────────────────────── B 题注居中
CAP_RE = re.compile(r'^(图|表)(\d+)-(\d+)\s*(.*)$')
BADPUNCT = '。？！，；：'

def stage_B():
    """将所有图表题注设置为居中对齐"""
    global W
    spans = para_spans(W)
    fixed = 0
    # 逆序处理，保证位置偏移不影响前面的段落
    for a, b in reversed(spans):
        seg = W[a:b]
        # 跳过表格内段落
        txt = _html.unescape(''.join(re.findall(r'<w:t(?: [^>]*)?>(.*?)</w:t>', seg, re.S))).strip()
        if len(txt) > 45:
            continue
        m = CAP_RE.match(txt)
        if not m:
            continue
        rest = m.group(4).strip()
        if not rest or any(c in rest for c in BADPUNCT) or len(rest) > 32:
            continue
        # 确认是题注，检查对齐
        if '<w:jc w:val="center"/>' in seg:
            continue
        if '<w:jc ' in seg:
            new_seg = re.sub(r'<w:jc w:val="[^"]+"/>', '<w:jc w:val="center"/>', seg)
        elif '<w:pPr>' in seg:
            new_seg = seg.replace('<w:pPr>', '<w:pPr><w:jc w:val="center"/>', 1)
        else:
            new_seg = seg.replace('<w:p>', '<w:p><w:pPr><w:jc w:val="center"/></w:pPr>', 1)
            new_seg = re.sub(r'<w:p [^>]+>', lambda m: m.group(0) + '<w:pPr><w:jc w:val="center"/></w:pPr>', new_seg, count=1)
        W = W[:a] + new_seg + W[b:]
        fixed += 1
    log('【B】题注居中修复：调整 %d 处' % fixed)


# ─────────────────────────────── C 标题样式检查与修复
def stage_C():
    """确保所有标题具有正确的层级样式"""
    global W
    spans = para_spans(W)
    fixed = 0
    for a, b in reversed(spans):
        seg = W[a:b]
        txt = _html.unescape(''.join(re.findall(r'<w:t(?: [^>]*)?>(.*?)</w:t>', seg, re.S))).strip()
        target_style = None
        if re.match(r'^任务11\.\d+\s', txt) or txt in ['【教学导读】', '【情景导入】', '【项目总结】', '【实践报告】', '【创新拓展】', '【综合测评】']:
            target_style = '4'
        elif re.match(r'^11\.\d+\.\d+\s', txt) or txt in ['一、能力测评', '二、素质测评', '三、参考答案（要点）']:
            target_style = '5'
        
        if target_style:
            m_st = re.search(r'<w:pStyle w:val="([^"]+)"/>', seg)
            cur_style = m_st.group(1) if m_st else None
            if cur_style != target_style:
                if m_st:
                    new_seg = re.sub(r'<w:pStyle w:val="[^"]+"/>', f'<w:pStyle w:val="{target_style}"/>', seg)
                elif '<w:pPr>' in seg:
                    new_seg = seg.replace('<w:pPr>', f'<w:pPr><w:pStyle w:val="{target_style}"/>', 1)
                else:
                    new_seg = seg.replace('<w:p>', f'<w:p><w:pPr><w:pStyle w:val="{target_style}"/></w:pPr>', 1)
                W = W[:a] + new_seg + W[b:]
                fixed += 1
    log('【C】标题样式修复：%d 处' % fixed)


