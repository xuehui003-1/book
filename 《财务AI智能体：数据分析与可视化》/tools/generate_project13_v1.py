def xml_esc(s):
    return s.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;').replace('"', '&quot;')

def P(text, style='1', jc=None):
    """生成段落 XML"""
    t_esc = xml_esc(text)
    ppr = '<w:pPr>'
    if style:
        ppr += f'<w:pStyle w:val="{style}"/>'
    if jc:
        ppr += f'<w:jc w:val="{jc}"/>'
    ppr += '</w:pPr>'
    r = f'<w:r><w:t>{t_esc}</w:t></w:r>'
    return f'<w:p>{ppr}{r}</w:p>'

def TBL(headers, rows, col_widths=None):
    """生成标准三线表 XML，表头具有 w:tblHeader 属性"""
    tbl = '<w:tbl>'
    tbl += '<w:tblPr><w:tblW w:w="5000" w:type="pct"/>'
    tbl += '<w:tblBorders>'
    tbl += '<w:top w:val="single" w:sz="6" w:space="0" w:color="auto"/>'
    tbl += '<w:bottom w:val="single" w:sz="6" w:space="0" w:color="auto"/>'
    tbl += '<w:left w:val="none"/><w:right w:val="none"/>'
    tbl += '<w:insideH w:val="single" w:sz="4" w:space="0" w:color="E2E8F0"/>'
    tbl += '<w:insideV w:val="none"/>'
    tbl += '</w:tblBorders>'
    tbl += '<w:tblLayout w:type="autofit"/>'
    tbl += '</w:tblPr>'
    
    # 表头行
    tbl += '<w:tr><w:trPr><w:tblHeader/></w:trPr>'
    for h in headers:
        tbl += f'<w:tc><w:p><w:pPr><w:jc w:val="center"/></w:pPr><w:r><w:rPr><w:b/></w:rPr><w:t>{xml_esc(h)}</w:t></w:r></w:p></w:tc>'
    tbl += '</w:tr>'
    
    # 数据行
    for r in rows:
        tbl += '<w:tr>'
        for c in r:
            tbl += f'<w:tc><w:p><w:r><w:t>{xml_esc(str(c))}</w:t></w:r></w:p></w:tc>'
        tbl += '</w:tr>'
    
    tbl += '</w:tbl>'
    return tbl

