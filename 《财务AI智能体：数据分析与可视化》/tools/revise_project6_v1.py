def rewrite_para_loose(raw, needle, parts):
    """整段重建。needle 必须是**整段原文**，否则报错——
    见 11_ C18：needle 取段中短语会在整段重建时静默吞掉段首/段尾。"""
    new = parts[0][0] if parts else ''
    i, a, b = find_para_loose(raw, needle)
    t = para_text(raw, a, b).strip()
    if norm_quotes(t) != norm_quotes(needle):
        raise ValueError('needle 不是整段（会吞掉段首/段尾）：%s\n  段原文：%s' % (new[:24], t[:80]))
    return raw[:a] + build_para(raw[a:b], parts) + raw[b:], i


def build_para_lines(seg, lines):
    """整段重建，但每个元素一行、行间用 <w:br/>（保留 pPr / paraId / rPr）"""
    pid = re.search(r'w14:paraId="[^"]*"', seg)
    pid = ' ' + pid.group(0) if pid else ''
    ppr = re.search(r'<w:pPr>.*?</w:pPr>', seg, re.S)
    ppr = ppr.group(0) if ppr else ''
    rpr = re.search(r'<w:rPr>.*?</w:rPr>', seg, re.S)
    rpr = rpr.group(0) if rpr else ('<w:rPr><w:rFonts w:ascii="Times New Roman"'
                                    ' w:hAnsi="Times New Roman" w:eastAsia="微软雅黑"/><w:sz w:val="24"/></w:rPr>')
    out = ['<w:p%s>%s' % (pid, ppr)]
    for k, ln in enumerate(lines):
        br = '<w:br/>' if k else ''
        out.append('<w:r>%s%s<w:t xml:space="preserve">%s</w:t></w:r>' % (rpr, br, _html.escape(ln, quote=False)))
    out.append('</w:p>')
    return ''.join(out)


