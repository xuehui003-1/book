def stage_C():
    global W
    # 【情景导入】的两个小标题（老方的"表格地狱"、情景思考）在项目1/2 里是样式5，
    # 但本册样式5 将被 3.x.x 占用（they are 标题2=4）。核对项目2：情景导入小标题=5，
    # 而 3.x.x=4、正文小标题=5 —— 保持与项目2 一致：情景点标题维持 5 不动。
    keep = set()
    for i, (a, b) in enumerate(para_spans(W)):
        t = para_text(W, a, b).strip()
        if t in ('老方的“表格地狱”', '情景思考', '老方的”表格地狱”'):
            # 引号已修，写死两种以防顺序问题
            keep.add(i if t == '情景思考' else i)
    changes = 0
    edits = []
    for i, (a, b) in enumerate(para_spans(W)):
        t = para_text(W, a, b).strip()
        if not t:
            continue
        m = re.search(r'w:pStyle w:val="(\d+)"', W[a:b])
        if not m:
            continue
        old = m.group(1)
        new = None
        if old == '4' and re.match(r'^任务3\.\d', t):
            new = '2'
        elif old == '5' and re.match(r'^3\.\d+\.\d+', t):
            new = '4'
        elif old == '6' and re.match(r'^\d+\.\s*', t) and i not in keep:
            new = '5'
        if new:
            edits.append((a, b, old, new, t))
    for a, b, old, new, t in sorted(edits, reverse=True):
        seg = re.sub(r'(w:pStyle w:val=")%s(")' % old, r'\g<1>%s\g<2>' % new, W[a:b], count=1)
        W = W[:a] + seg + W[b:]
        changes += 1
    log('【C】标题层级修正：%d 处（任务3.x 4→2；3.x.x 5→4；"1." 6→5）' % changes)


