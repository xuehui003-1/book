def main():
    global W
    shutil.rmtree(WORK, ignore_errors=True)
    os.makedirs(WORK + '/out', exist_ok=True)
    Z = zipfile.ZipFile(SRC)
    names = Z.namelist()
    Z.extractall(WORK + '/work')
    W = open(WORK + '/work/word/document.xml', encoding='utf-8').read()

    log('【一】按编辑批注② 改读者视角（6 处）')
    stage_reader()
    log('\n【二】按编辑批注⑥ 完善内容（1 处）')
    stage_dify()

    # 断言：第三人称指向已清除
    import html as _h
    full = _h.unescape(''.join(re.findall(r'<w:t(?: [^>]*)?>(.*?)</w:t>', W, re.S)))
    left = {k: full.count(k) for k in ['学生', '学习者', '读者', '笔者', '编者', '教师'] if full.count(k)}
    log('\n  断言：第三人称指向词残留 %s' % (left if left else '0（已清零）'))

    open(WORK + '/work/word/document.xml', 'w', encoding='utf-8').write(W)
    out = WORK + '/out/' + SRC.replace('V1', 'V2')
    with zipfile.ZipFile(out, 'w', zipfile.ZIP_DEFLATED) as zo:
        for n in names:
            zo.write(os.path.join(WORK + '/work', n), n)
    log('\n文档已生成：%s  (%.1f KB)   共 %d 项' % (out, os.path.getsize(out) / 1024, len(LOG)))


if __name__ == '__main__':
    main()
